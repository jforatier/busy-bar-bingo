/** { en: { 1: [text, width], … }, fr: { 22: […], … } } */
export function nicknames() {
  registerFontMaps(small);
  const out = {};
  for (const [lang, list] of Object.entries(NICKNAMES)) {
    out[lang] = {};
    const entries = Array.isArray(list) ? list.map((s, i) => [i + 1, s]) : Object.entries(list);
    for (const [n, s] of entries) out[lang][n] = [s, textWidth(s, 'small')];
  }
  return out;
}

export function writeNicknames() {
  const text = `// Generated by scripts/nicknames.mjs during the build: do not edit. [text, width in \`small\`] per number.\n` +
    `export const NICKNAMES: Record<string, Record<string, [string, number]>> = ${JSON.stringify(nicknames())};\n`;
  let old = '';
  try { old = readFileSync('src/nicknames.gen.ts', 'utf8'); } catch { /* first build */ }
  if (old !== text) writeFileSync('src/nicknames.gen.ts', text);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) writeNicknames();
