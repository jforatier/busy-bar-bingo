// The caller's voice: from the committed clips (voice/<lang>/<key>.pcm, 22 050 Hz, made by scripts/voice_gen.py) to
// the bar's .snd (44 100 Hz) as src/sounds/<lang>_<key>.snd, flat because `busy-cli build` packs the sub-folders of
// src/sounds/ into sounds/ itself (en/ and fr/ clips of the same name overwrote each other). Also writes
// src/voice.gen.ts with each clip's length: the bar has no "sound ended" event, so the app chains the letter and the
// number by their lengths. Called by vite.config.mjs during the build.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

export const LANGS = ['en', 'fr'];
/** Every clip a language must have: 1-90, the five column letters, the four prizes. */
export const KEYS = [...Array.from({ length: 90 }, (_, i) => `n${i + 1}`), ...'BINGO', 'bingo', 'line', 'two_lines', 'full_house'];

/** 22 050 Hz → 44 100 Hz s16le: each sample, then the midpoint to the next. */
export function double(pcm) {
  const n = pcm.length / 2;
  const out = Buffer.alloc(n * 4);
  for (let i = 0; i < n; i++) {
    const a = pcm.readInt16LE(i * 2);
    const b = i + 1 < n ? pcm.readInt16LE(i * 2 + 2) : a;
    out.writeInt16LE(a, i * 4);
    out.writeInt16LE(Math.round((a + b) / 2), i * 4 + 2);
  }
  return out;
}

function writeIfChanged(path, data) {
  let old = null;
  try { old = readFileSync(path); } catch { /* first build */ }
  if (!old || !old.equals(Buffer.from(data))) writeFileSync(path, data);
}

export function buildVoice() {
  const ms = {};
  for (const lang of LANGS) {
    const have = new Set(readdirSync(`voice/${lang}`).filter((f) => f.endsWith('.pcm')).map((f) => f.slice(0, -4)));
    const missing = KEYS.filter((k) => !have.has(k));
    if (missing.length) throw new Error(`voice/${lang}: missing ${missing.join(', ')}`);
    mkdirSync('src/sounds', { recursive: true });
    ms[lang] = {};
    for (const key of KEYS) {
      const pcm = readFileSync(`voice/${lang}/${key}.pcm`);
      ms[lang][key] = Math.round((pcm.length / 2 / 22050) * 1000);
      writeIfChanged(`src/sounds/${lang}_${key}.snd`, double(pcm));
    }
  }
  writeIfChanged('src/voice.gen.ts',
    `// Generated by scripts/voice.mjs during the build: do not edit. Length of each voice clip, in ms.\nexport const VOICE_MS = ${JSON.stringify(ms)} as const;\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) buildVoice();
